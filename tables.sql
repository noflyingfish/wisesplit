-- ============================================================================
-- MONEY — DECIMAL(12,2). READ BEFORE POINTING THE APP AT THIS DATABASE.
--
-- The four money columns are exact decimal:
--     Expense.amount           DECIMAL(12,2)
--     ExpenseShare.amount      DECIMAL(12,2)
--     ExpenseShare.percentage  DECIMAL(5,2)
--     Settlement.amount        DECIMAL(12,2)
--
-- WHY. Money was previously stored as Float, and the app's rounding idiom was
-- `Math.round(n * 100) / 100`, which is not exact. Measured against true
-- decimal rounding it disagrees on ordinary inputs:
--     Math.round(1.005 * 100) / 100  ->  1.00    but 1.005 to 2dp is 1.01
--     Math.round(4.015 * 100) / 100  ->  4.01    but 4.015 to 2dp is 4.02
-- so the effective rule was "whatever the binary representation happens to
-- do" — unreproducible, and reachable from an ordinary percentage split
-- (10% of $10.05 is exactly $1.005). DECIMAL removes the class entirely.
--
-- (12,2) is 10 integer digits + 2 decimal: up to 9,999,999,999.99. About $10bn
-- of headroom on a holiday-expenses app — you will never think about it again.
--
-- *** THE APP WILL NOT READ THIS CORRECTLY UNTIL THE REFACTOR LANDS. ***
-- Prisma returns DECIMAL as a Decimal OBJECT, not a JS number. Until the code
-- is refactored, this breaks:
--   - `a + b`: STRING CONCATENATION. 10.05 + 5.02 is "10.055.02", not 15.07.
--   - `a - b` / `a * n` / `a / n`: silently coerced through a float, so the
--     exactness is lost (10.05 - 5.02 is 5.030000000000001).
--   - `typeof x === "number"`: FALSE for every Decimal, with no error anywhere.
--     `edit/page.tsx`'s `typeof s.percentage === "number"` therefore silently
--     dropped stored percentages and invisibly regressed the S-2 fix. This is
--     the failure that produces no signal.
--   - JSON serialisation: a Decimal reaches the client as a STRING ("12.34").
--   - React server -> client props: a Decimal throws outright ("Only plain
--     objects can be passed to Client Components... Decimal objects are not
--     supported").
-- Use .plus() / .minus() / .times() / .comparedTo() / .toDecimalPlaces(2)
-- instead, and convert at the edges.
--
-- CORRECTED 2026-09-24, after this migration was implemented and measured on the
-- real stack (Prisma 6.19.3 / decimal.js). An earlier version of this note also
-- claimed Math.abs / Math.round / Math.min / Math.max "break", that
-- Intl.NumberFormat fails, and that .toFixed() throws. **They do not.** All of
-- them coerce through `valueOf()` (or, for toFixed, are Decimal methods in their
-- own right) and appear to work: Math.abs(Decimal) is 12.34, Intl formats a
-- Decimal to "$12.34", and `new Decimal("10.05").toFixed(2)` is "10.05". They are
-- the more dangerous paths precisely because they keep producing plausible
-- answers instead of errors, but they do not throw and do not return NaN. The
-- list above is the measured one; the helper that replaces them is `lib/money.ts`.
--
-- Measured scope of that refactor (2026-09-22): the money engine is 572 lines
-- across 5 files — lib/utils.ts, lib/balance.ts, lib/expense-shares.ts,
-- expenses/_actions.ts, settle/_actions.ts. There are 21 formatCurrency call
-- sites, all absorbed by making that one function accept Decimal; only 9
-- Prisma money reads; 16 landmine occurrences in total.
--
-- The Prisma schema must change to match, in the same pass:
--     provider    = "sqlite"  ->  "mysql"
--     amount      Float       ->  Decimal  @db.Decimal(12, 2)
--     percentage  Float?      ->  Decimal? @db.Decimal(5, 2)
-- Pin the precision explicitly: a bare Prisma `Decimal` maps to DECIMAL(65,30)
-- and `db pull` would widen these columns back to that.
--
-- LOADING THIS SCHEMA NOW IS FINE — it only creates tables. The app simply
-- must not be pointed at this database until the code is updated.
